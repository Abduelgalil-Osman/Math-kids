function arNum(n){
  var o=["صفر","واحد","اثنان","ثلاثة","أربعة","خمسة","ستة","سبعة","ثمانية","تسعة","عشرة","أحد عشر","اثنا عشر"];
  if(n<=12) return o[n];
  if(n<20) return o[n-10]+" عشر";
  if(n<100){ var d=n%10,f=Math.floor(n/10);
    var tn=["","عشرة","عشرون","ثلاثون","أربعون","خمسون","ستون","سبعون","ثمانون","تسعون"];
    return d===0?tn[f]:o[d]+" و"+tn[f]; }
  if(n<1000){ var h=Math.floor(n/100),r=n%100;
    var hs=["","مئة","مئتان","ثلاث مئة","أربع مئة","خمس مئة","ست مئة","سبع مئة","ثمان مئة","تسع مئة"];
    return r===0?hs[h]:hs[h]+" و"+arNum(r); }
  var th=Math.floor(n/1000),rr=n%1000,ts=th===1?"ألف":th===2?"ألفان":th<=10?o[th]+" آلاف":arNum(th)+" ألف";
  return rr===0?ts:ts+" و"+arNum(rr);
}

